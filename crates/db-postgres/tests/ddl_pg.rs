//! DDL generation against the disposable server (`scripts/test-pg.sh up` and `seed`).
//!
//! Round trip: generate a schema's DDL, apply it to an empty database, generate again there, and
//! require the same text. Anything the generator captures must survive the trip.

use std::sync::Arc;
use std::time::Duration;

use quarry_db_core::{
    ConnectParams, DatabaseAdapter, DdlObject, DdlOptions, ExecOptions, Isolation, ObjectRef,
    ObjectType, Session, TlsMode, TxMode, TxSettings, TxStatus,
};
use quarry_db_postgres::PostgresAdapter;
use quarry_secrets::SecretString;

fn params(database: &str) -> ConnectParams {
    let pw_file = format!(
        "{}/../../target/test-pg/password",
        env!("CARGO_MANIFEST_DIR")
    );
    let password = std::fs::read_to_string(&pw_file)
        .unwrap_or_else(|e| panic!("{pw_file}: {e} (run scripts/test-pg.sh up)"))
        .trim()
        .to_owned();
    ConnectParams {
        host: "127.0.0.1".into(),
        port: 55432,
        database: database.into(),
        username: "quarry".into(),
        password: Some(SecretString::new(password)),
        tls: TlsMode::Disable,
        connect_timeout: Duration::from_secs(5),
        read_only: false,
        application_name: "quarry-it-ddl".into(),
        options: Default::default(),
    }
}

async fn admin(database: &str) -> tokio_postgres::Client {
    let p = params(database);
    let mut cfg = tokio_postgres::Config::new();
    cfg.host(&p.host)
        .port(p.port)
        .user(&p.username)
        .dbname(&p.database)
        .password(p.password.as_ref().expect("pw").expose());
    let (client, conn) = cfg
        .connect(tokio_postgres::NoTls)
        .await
        .expect("admin connect");
    tokio::spawn(conn);
    client
}

async fn session(database: &str) -> Arc<dyn Session> {
    PostgresAdapter
        .connect(&params(database), Box::new(|_| {}))
        .await
        .expect("connect")
}

/// A fresh, empty database for one test, dropped first if it exists.
async fn empty_database(name: &str) {
    let db = admin("quarry_test").await;
    db.batch_execute(&format!("DROP DATABASE IF EXISTS {name} WITH (FORCE)"))
        .await
        .expect("drop");
    db.batch_execute(&format!("CREATE DATABASE {name}"))
        .await
        .expect("create");
}

async fn drop_database(name: &str) {
    let db = admin("quarry_test").await;
    let _ = db
        .batch_execute(&format!("DROP DATABASE IF EXISTS {name} WITH (FORCE)"))
        .await;
}

fn schema(name: &str) -> Vec<DdlObject> {
    vec![DdlObject::Schema {
        schema: name.into(),
    }]
}

