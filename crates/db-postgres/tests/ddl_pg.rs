/// What the server holds for a schema: every column, constraint, index (partition indexes
/// included), trigger, routine and relation, as text. Compares databases, not generator output.
async fn fingerprint(database: &str, schema_name: &str) -> String {
    let db = admin(database).await;
    db.batch_execute("SET search_path = ''")
        .await
        .expect("path");
    db.query_one(
        "SELECT string_agg(x, E'\\n' ORDER BY x) FROM (
           SELECT 'rel ' || c.oid::regclass || ' ' || c.relkind::text || ' '
                  || coalesce(obj_description(c.oid, 'pg_class'), '')
           FROM pg_class c WHERE c.relnamespace = $1::text::regnamespace
           UNION ALL
           SELECT 'col ' || a.attrelid::regclass || ' ' || a.attname || ' '
                  || format_type(a.atttypid, a.atttypmod) || ' ' || a.attnotnull::text || ' '
                  || a.attidentity::text || a.attgenerated::text || ' '
                  || coalesce(pg_get_expr(d.adbin, d.adrelid), '')
           FROM pg_attribute a
           JOIN pg_class c ON c.oid = a.attrelid AND c.relnamespace = $1::text::regnamespace
           LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
           WHERE a.attnum > 0 AND NOT a.attisdropped
           UNION ALL
           SELECT 'idx ' || i.tablename || ' ' || i.indexdef
           FROM pg_indexes i WHERE i.schemaname = $1::text
           UNION ALL
           SELECT 'con ' || k.conrelid::regclass || ' ' || k.conname || ' '
                  || pg_get_constraintdef(k.oid)
           FROM pg_constraint k WHERE k.connamespace = $1::text::regnamespace
           UNION ALL
           SELECT 'trg ' || pg_get_triggerdef(t.oid) || ' ' || t.tgenabled::text
           FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
           WHERE c.relnamespace = $1::text::regnamespace AND NOT t.tgisinternal
           UNION ALL
           SELECT 'fn ' || p.oid::regprocedure || ' ' || md5(pg_get_functiondef(p.oid))
           FROM pg_proc p WHERE p.pronamespace = $1::text::regnamespace AND p.prokind <> 'a'
         ) t(x)",
        &[&schema_name],
    )
    .await
    .expect("fingerprint")
    .get(0)
}

async fn round_trip(schema_name: &str, target: &str) -> String {
    let source = session("quarry_test").await;
    let script = source
        .ddl(&schema(schema_name), &DdlOptions::default())
        .await
        .expect("generate");
    empty_database(target).await;
    admin(target)
        .await
        .batch_execute(&script)
        .await
        .unwrap_or_else(|e| panic!("script did not apply: {e:?}\n---\n{script}"));
    let regenerated = session(target)
        .await
        .ddl(&schema(schema_name), &DdlOptions::default())
        .await
        .expect("regenerate");
    assert_eq!(
        regenerated, script,
        "DDL changed across the round trip:\n--- source\n{script}\n--- target\n{regenerated}"
    );
    let (before, after) = (
        fingerprint("quarry_test", schema_name).await,
        fingerprint(target, schema_name).await,
    );
    assert_eq!(after, before, "the databases differ after the round trip");
    script
}

#[tokio::test]
#[ignore = "needs scripts/test-pg.sh up and seed"]
async fn seeded_shop_schema_round_trips() {
    let script = round_trip("shop", "quarry_ddl_shop").await;
    for expected in [
        "CREATE SCHEMA shop;",
        "COMMENT ON SCHEMA shop IS 'Sample data for manual testing';",
        "CREATE SEQUENCE shop.orders_id_seq AS bigint",
        "CREATE TABLE shop.order_items (",
        "CONSTRAINT order_items_pkey PRIMARY KEY (order_id, product_id)",
        "ALTER SEQUENCE shop.orders_id_seq OWNED BY shop.orders.id;",
        "CREATE INDEX orders_customer_idx ON shop.orders USING btree (customer_id, placed_at DESC);",
        "ADD CONSTRAINT order_items_order_id_fkey FOREIGN KEY (order_id) REFERENCES shop.orders(id) ON DELETE CASCADE;",
        "CREATE MATERIALIZED VIEW shop.daily_sales AS",
    ] {
        assert!(
            script.contains(expected),
            "missing {expected:?} in\n{script}"
        );
    }
    // Sequences come before the tables whose defaults use them.
    let seq = script
        .find("CREATE SEQUENCE shop.orders_id_seq")
        .expect("seq");
    let table = script.find("CREATE TABLE shop.orders (").expect("table");
    assert!(seq < table);
    drop_database("quarry_ddl_shop").await;
}

#[tokio::test]
#[ignore = "needs scripts/test-pg.sh up"]
async fn rich_schema_round_trips_with_odd_names_and_cycles() {
    admin("quarry_test")
        .await
        .batch_execute(FIXTURE)
        .await
        .expect("fixture");
    let script = round_trip("it_ddl", "quarry_ddl_rich").await;
    for expected in [
        "SET check_function_bodies = false;",
        "CREATE SEQUENCE it_ddl.invoice_no AS integer\n    START WITH 100\n    INCREMENT BY 5\n    MINVALUE 100\n    MAXVALUE 100000\n    CACHE 2\n    CYCLE;",
        r#"CREATE TABLE it_ddl."Odd ""Orders""" ("#,
        "id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL",
        r#"name text COLLATE "C""#,
        "slug text GENERATED ALWAYS AS (it_ddl.slug(name)) STORED",
        "COMMENT ON COLUMN it_ddl.customers.email IS 'Login, unique per person';",
        "CREATE UNIQUE INDEX customers_email_key ON it_ddl.customers USING btree (lower(email));",
        "WHERE (created > '2020-01-01 00:00:00+00'::timestamp with time zone);",
        "CREATE TABLE it_ddl.events_2024 PARTITION OF it_ddl.events\n    FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');",
        "PARTITION BY RANGE (at);",
        "CREATE VIEW it_ddl.big_order_count WITH (security_barrier=true) AS",
        "ALTER TABLE it_ddl.a\n    ADD CONSTRAINT a_b_fkey FOREIGN KEY (b_id) REFERENCES it_ddl.b(id);",
        r#"ALTER TABLE it_ddl."Odd ""Orders""" DISABLE TRIGGER orders_audit;"#,
        "COMMENT ON FUNCTION it_ddl.touch() IS 'Keeps quantities positive';",
        "CREATE OR REPLACE PROCEDURE it_ddl.archive(",
    ] {
        assert!(
            script.contains(expected),
            "missing {expected:?} in\n{script}"
        );
    }
    // The partitioned index is created with plain ON, so the partition gets (and attaches) its
    // own; the partition's index is not listed separately.
    assert!(
        script.contains("CREATE INDEX events_at ON it_ddl.events USING btree (at);"),
        "{script}"
    );
    assert!(!script.contains("ON ONLY"), "{script}");
    assert!(!script.contains("events_2024_at_idx"), "{script}");
    // Views come after the views they read.
    let base = script
        .find("CREATE VIEW it_ddl.big_orders AS")
        .expect("base view");
    let top = script
        .find("CREATE VIEW it_ddl.big_order_count")
        .expect("dependent view");
    assert!(base < top);
    // A routine taking a table's row type waits for the table.
    let table = script
        .find("CREATE TABLE it_ddl.customers (")
        .expect("customers");
    let rowtype_fn = script
        .find("FUNCTION it_ddl.order_count(")
        .expect("order_count");
    assert!(table < rowtype_fn);
    drop_database("quarry_ddl_rich").await;
}

#[tokio::test]
#[ignore = "needs scripts/test-pg.sh up and seed"]
async fn single_objects_options_and_errors() {
    let s = session("quarry_test").await;
    let options = DdlOptions::default();

    // One table brings its serial sequence and ownership along.
    let orders = s
        .ddl(
            &[DdlObject::Relation {
                schema: "shop".into(),
                name: "orders".into(),
            }],
            &options,
        )
        .await
        .expect("table");
    assert!(
        orders.starts_with("CREATE SEQUENCE shop.orders_id_seq"),
        "{orders}"
    );
    assert!(orders.contains("ALTER SEQUENCE shop.orders_id_seq OWNED BY shop.orders.id;"));
    assert!(!orders.contains("CREATE TABLE shop.customers"), "{orders}");

    // Bare names in the object's own schema; other schemas stay qualified.
    let bare = s
        .ddl(
            &[DdlObject::Relation {
                schema: "shop".into(),
                name: "orders".into(),
            }],
            &DdlOptions {
                qualify: false,
                ..options
            },
        )
        .await
        .expect("unqualified");
    assert!(bare.contains("CREATE TABLE orders ("), "{bare}");
    assert!(bare.contains("REFERENCES customers(id)"), "{bare}");

    let owned = s
        .ddl(
            &[DdlObject::Relation {
                schema: "shop".into(),
                name: "customers".into(),
            }],
            &DdlOptions {
                owner: true,
                grants: true,
                ..options
            },
        )
        .await
        .expect("owner");
    assert!(
        owned.contains("ALTER TABLE shop.customers OWNER TO quarry;"),
        "{owned}"
    );

    let index = s
        .ddl(
            &[DdlObject::Index {
                schema: "shop".into(),
                name: "orders_customer_idx".into(),
            }],
            &options,
        )
        .await
        .expect("index");
    assert_eq!(
        index,
        "CREATE INDEX orders_customer_idx ON shop.orders USING btree (customer_id, placed_at DESC);\n"
    );

    let missing = s
        .ddl(
            &[DdlObject::Relation {
                schema: "shop".into(),
                name: "nope".into(),
            }],
            &options,
        )
        .await
        .expect_err("missing");
    assert!(
        missing.message.contains("shop.nope does not exist"),
        "{missing:?}"
    );

    // Generation never touches the session's own transaction.
    s.set_tx_settings(TxSettings {
        mode: TxMode::Manual,
        isolation: Isolation::ReadCommitted,
    });
    s.execute("select 1", &ExecOptions::default())
        .await
        .expect("open a transaction");
    assert_eq!(s.tx_status(), TxStatus::Active);
    s.ddl(&schema("shop"), &options).await.expect("ddl");
    assert_eq!(s.tx_status(), TxStatus::Active);
    let details = s
        .object_details(&ObjectRef {
            schema: "shop".into(),
            name: "orders".into(),
            object_type: ObjectType::Table,
        })
        .await
        .expect("session still usable");
    assert!(details.is_some());
    s.rollback().await.expect("rollback");
}
