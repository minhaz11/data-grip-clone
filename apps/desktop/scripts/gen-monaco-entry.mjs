// Generates src/features/editor/monaco/entry.ts: Monaco's editor.main.js without its ~80 bundled
// languages and language services, plus only the PostgreSQL tokenizer. Rerun after upgrading
// monaco-editor:  node scripts/gen-monaco-entry.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../node_modules/monaco-editor/', import.meta.url));
const version = JSON.parse(readFileSync(`${root}package.json`, 'utf8')).version;
const main = readFileSync(`${root}esm/vs/editor/editor.main.js`, 'utf8');

const imports = main
  .split('\n')
  .filter((l) => l.startsWith("import '") && !l.includes('/languages/'))
  .map((l) =>
    l
      .replace("import './", "import 'monaco-esm/editor/")
      .replace("import '../", "import 'monaco-esm/"),
  );
const exportLine = main
  .split('\n')
  .find((l) => l.startsWith('export {') && l.includes("'./editor.api.js'"));
if (!exportLine || imports.length < 50)
  throw new Error('editor.main.js layout changed; review this script');

const out = [
  `// GENERATED by scripts/gen-monaco-entry.mjs from monaco-editor ${version}. Do not edit.`,
  '// Editor features only; languages are opt-in below.',
  ...imports,
  "import 'monaco-esm/languages/definitions/pgsql/register.js';",
  exportLine.replace("'./editor.api.js'", "'monaco-esm/editor/editor.api.js'"),
  '',
].join('\n');
writeFileSync(
  fileURLToPath(new URL('../src/features/editor/monaco/entry.ts', import.meta.url)),
  out,
);
console.log(`entry.ts: ${imports.length} feature imports from monaco-editor ${version}`);
